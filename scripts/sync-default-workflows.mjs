/**
 * Generate `src/generated/default-workflows.ts` from `docs/workflows/*.json`.
 *
 * The pack is the single source of truth: it is what ships for download and what
 * the plugin prefills. Generating the module keeps the two from drifting, and
 * `tests/default-workflows.spec.ts` fails if this file is stale.
 *
 * Usage: node scripts/sync-default-workflows.mjs
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const packDir = path.join(root, 'docs', 'workflows')
const outFile = path.join(root, 'src', 'generated', 'default-workflows.ts')

/** Pretty names users see in the workbench instead of the file name. */
const LABELS = {
  'qwen-image-create.json': 'Qwen Image 2.1 - create (adjustable size)',
  'qwen-image-cutout.json': 'Qwen Image 2.1 - cutout (RGBA)',
  'qwen-image-edit.json': 'Qwen Image 2.1 - edit',
  'qwen-image-remove-bg.json': 'Qwen Image 2.1 - remove background',
}

const files = readdirSync(packDir).filter(name => name.endsWith('.json')).sort()
if (files.length === 0) throw new Error('docs/workflows has no JSON files')

const entries = files.map(file => {
  const json = readFileSync(path.join(packDir, file), 'utf8').replace(/^\uFEFF/, '')
  return {
    file,
    name: LABELS[file] ?? file.replace(/\.json$/, ''),
    json: JSON.stringify(JSON.parse(json)),
  }
})

const body = `/**
 * GENERATED by scripts/sync-default-workflows.mjs - do not edit.
 *
 * The workflows below are prefilled into a fresh configuration so a new install
 * has a working ComfyUI setup without hunting for files. Source of truth:
 * docs/workflows/*.json.
 */
export interface ShippedWorkflow {
  /** Pack file name, for traceability. */
  file: string
  /** Display name used as the workflow label. */
  name: string
  /** API-format workflow JSON. */
  json: string
}

export const SHIPPED_WORKFLOWS: readonly ShippedWorkflow[] = ${JSON.stringify(entries, null, 2)}
`

mkdirSync(path.dirname(outFile), { recursive: true })
writeFileSync(outFile, body, 'utf8')
console.log(`default-workflows: ${String(entries.length)} workflows from docs/workflows -> ${path.relative(root, outFile)}`)
